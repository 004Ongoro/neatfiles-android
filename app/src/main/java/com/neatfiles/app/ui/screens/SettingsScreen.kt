@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun SettingsScreen(
    state: MainUiState,
    onBackClick: () -> Unit,
    onOldThresholdChange: (Int) -> Unit,
    onToggleScheduledCleanup: (Boolean) -> Unit,
    onReRunOnboarding: () -> Unit,
    onLicensesClick: () -> Unit,
